    done

    local menu=""
    for base in $(echo "${!PROJECT_GROUPS[@]}" | tr ' ' '\n' | sort); do
        local sessions="${PROJECT_GROUPS[$base]}"
        local count=$(echo "$sessions" | wc -w)
        local marker=" "
        for s in $sessions; do
            [ "$s" = "$CURRENT_SESSION" ] && marker=">" && break
        done
        truncate_str "$base" 22; local tbase="$REPLY"
        printf -v line "%s  %-22s  %d session%s" "$marker" "$tbase" "$count" "$([ $count -gt 1 ] && echo 's' || echo '')"
        [ -n "$menu" ] && menu="${menu}"$'\n'"${line}" || menu="${line}"
    done

    local selected=$(echo "$menu" | fzf \
        --multi --reverse --no-info \
        --header="Tab=select  Enter=close  Esc=back" \
        --prompt="close > " --pointer=">" --marker="x" --border=none \
        --preview="base=\$(echo {} | sed 's/^[^ ]* *//' | sed 's/  .*//' | xargs); echo \"\$base sessions:\"; echo; tmux list-sessions -F '#{session_name}' 2>/dev/null | grep \"^\${base}\" | while read s; do ppath=\$(tmux display-message -t \"\$s\" -p '#{pane_current_path}' 2>/dev/null | sed \"s|\$HOME|~|\"); cmd=\$(tmux list-panes -t \"\$s\" -F '#{pane_current_command}' 2>/dev/null | head -1); echo \"  \$s  (\$cmd)  \$ppath\"; done" \
        --preview-window=down,40%,wrap \
        --color="fg:-1,bg:-1,hl:-1:underline,fg+:0:bold,bg+:7,hl+:1:bold:underline,info:-1,prompt:-1,pointer:-1,marker:-1,spinner:-1,header:-1:dim,border:-1,preview-fg:-1,preview-bg:-1,gutter:-1")

    [ -z "$selected" ] && return 0

    local to_kill=""
    while read -r line; do
        local base=$(echo "$line" | sed 's/^[^ ]* *//' | sed 's/  .*//' | xargs)
        to_kill+="${PROJECT_GROUPS[$base]}"
    done <<< "$selected"

    for s in $to_kill; do
        [ "$s" != "$CURRENT_SESSION" ] && kill_with_history "$s" "close-menu"
    done

    if [[ " $to_kill " == *" $CURRENT_SESSION "* ]]; then
        local other=$(tmux list-sessions -F '#{session_name}' 2>/dev/null | grep -v "^${CURRENT_SESSION}$" | head -1)
        if [ -n "$other" ]; then
            tmux switch-client -t "$other"
            kill_with_history "$CURRENT_SESSION" "close-menu"
            CURRENT_SESSION="$other"
        fi
    fi
    return 1
}

# ── Extract session name from display line ──
# Primary path: read the hidden field after the trailing TAB (full name, untruncated).
# Fallback: parse the visible portion (legacy path; ignore tree chars + markers).
extract_name() {
    local line="$1"
    case "$line" in
        *$'\t'*) printf '%s' "${line##*$'\t'}"; return ;;
    esac
    echo "$line" | awk '{for(i=1;i<=NF;i++){if($i!=">" && $i!="*" && $i!="●" && $i!="○" && $i!="·" && $i!="§" && $i!="│" && $i!="├" && $i!="└" && $i!="✗" && $i!="L" && $i!="🔒"){print $i; exit}}}'
}

