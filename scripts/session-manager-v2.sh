            [ "${total_n:-0}" -gt 0 ] 2>/dev/null && pct=$((done_n * 100 / total_n))
            filled=$((pct * 10 / 100))
            [ "$filled" -gt 10 ] && filled=10
            pbar=""
            for ((i=0; i<10; i++)); do
                if [ "$i" -lt "$filled" ]; then pbar+="━"; else pbar+="─"; fi
