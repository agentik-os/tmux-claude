    DISPLAY_LIST+="  ◆ new claude          Claude Opus 4.7 (Anthropic)"$'\n'
    DISPLAY_LIST+="  ◆ new codex           Codex CLI (OpenAI)"$'\n'
    DISPLAY_LIST+="  ◆ new pi              Pi Agent (Earendil)"$'\n'
    DISPLAY_LIST+="  ◆ aisb terminal       Attach AISB bot logs"$'\n'
    DISPLAY_LIST+=" "$'\n'
    DISPLAY_LIST+="  open project          pick a project from projects.json"$'\n'
    DISPLAY_LIST+="  clean cache           drop kernel cache + /tmp junk (fast)"$'\n'
    DISPLAY_LIST+="  deep clean            heavy disk reclaim — npm/bun/pnpm/playwright/electron/journal/apt"$'\n'
    DISPLAY_LIST+="  clean history         wipe kill log + protection state"$'\n'
    DISPLAY_LIST+="  kill all              kill every session except the current one"$'\n'
    DATA_LINES="2 3 4 5 6 7 9 10 11 12 13"
    CURRENT_LINE=2

elif [ "$VIEW" = "help" ]; then
    # Help view: keyboard shortcuts + status icon legend, fully searchable.
    DISPLAY_LIST=""
    add_help_line() {
        DISPLAY_LIST+="${1}"$'\n'
        HELP_LN=$((HELP_LN+1))
        # Mark non-blank lines as data so down/up skip blank rows
        case "$1" in *[!\ ]*) DATA_LINES+="${HELP_LN} " ;; esac
    }
    HELP_LN=0
    add_help_line " "
    add_help_line "  Tabs"
    add_help_line "    ← / <        previous tab"
    add_help_line "    → / >        next tab  (sessions ↔ menu ↔ help)"
    add_help_line " "
    add_help_line "  Navigation"
    add_help_line "    ↑ / ↓        move between sessions (skips blanks + headers)"
    add_help_line "    Tab          jump to next project group"
    add_help_line "    ⇧Tab         spawn new ClaudeRoot session at \$HOME"
    add_help_line "    Enter        switch to selected session / run menu action"
    add_help_line "    Esc          close menu"
    add_help_line " "
    add_help_line "  Session actions"
    add_help_line "    x            kill selected session"
    add_help_line "    .            toggle kill protection (§ icon)"
    add_help_line "    §            refresh in-place — reloads list (progress, age, RAM) + preview"
    add_help_line "    ?            jump to this help tab"
    add_help_line " "
    add_help_line "  Status icons (column 2 of each session line)"
    add_help_line "    ●  working   Claude is actively running"
    add_help_line "    ○  idle      Claude at prompt, waiting for input"
    add_help_line "    ·  shell     no Claude in this session"
    add_help_line "    §  pinned    immune to orphan-killer and 'x' kill"
    add_help_line "    >  current   the session you are attached to"
    add_help_line "    *  attached  an attached client other than yours"
    add_help_line "    ✗  killed    session was closed"
    add_help_line " "
    add_help_line "  Tree glyphs (workers under their oracle)"
    add_help_line "    ├ / └        worker child of the oracle directly above"
    add_help_line "                 (drawn only when group has both oracle and worker)"
    add_help_line " "
    add_help_line "  Project groups"
    add_help_line "    Home         Home, Home-2, c-* (interactive sessions)"
    add_help_line "    <Project>    one header per project (Causio, Kommu, …)"
    add_help_line "    system       earthbit-*, AISB-* (orchestration daemons)"
    add_help_line " "
    add_help_line "  Auto-protect"
    add_help_line "    Working sessions are auto-protected. After 10 min idle,"
    add_help_line "    protection is removed. Manual '.' override is respected."
    CURRENT_LINE=2
    unset -f add_help_line

fi

    human_mb "$TOTAL_RAM"; TOTAL_RAM_STR="$REPLY"

    # Header: tabs (left) + stats (right) on line 1, underline on line 2.
    TAB_BAR=$(render_tabs "$VIEW")
    TAB_LINE1=$(printf '%s' "$TAB_BAR" | sed -n '1p')
    TAB_LINE2=$(printf '%s' "$TAB_BAR" | sed -n '2p')
    STATS_STR="cpu ${CPU}%   ram ${RAM}%   disk ${DISK}   ${TOTAL_RAM_STR}"

    # Compute right-aligned padding (visible chars only — strip ANSI from tab line)
    tab_visible=$(printf '%s' "$TAB_LINE1" | sed 's/\x1b\[[0-9;]*m//g')
    tab_w=$(LC_ALL=C.UTF-8 awk -v s="$tab_visible" 'BEGIN{print length(s)}')
    stats_w=${#STATS_STR}
    target_w=$((TERM_W - 4))      # match popup margin so stats never get cut off
    pad_n=$((target_w - tab_w - stats_w))
    [ "$pad_n" -lt 3 ] && pad_n=3
    pad=$(printf '%*s' "$pad_n" "")

    HEADER=" "$'\n'
    HEADER+="${TAB_LINE1}${pad}${STATS_STR}"$'\n'
    HEADER+="${TAB_LINE2}"$'\n'
    HEADER+=" "

    # Persist line numbers used by fzf bind helpers
    echo "$SECTION_POS" > /tmp/.sm-sections        # Tab section-cycle
    echo "$DATA_LINES"  > /tmp/.sm-data-lines      # Down/Up skip-empty
    echo 0 > /tmp/.sm-section-cursor

    # Preview command — skip menu items (open project / clean RAM / kill all / separators / group headers)
    # Preview: {2} = the hidden tab field that holds the full session name.
    # Empty for headers / blank lines / menu actions → no preview shown.
    PREVIEW_CMD='sess={2}; [ -n "$sess" ] && '"$HOME"'/.tmux/scripts/session-preview.sh "$sess" "'"$TMPDIR_SM"'"'

    # Render-only mode: dump DISPLAY_LIST to stdout (used by `reload(...)` bind on §)
    if [ "$SM_RENDER_MODE" = "list" ]; then
        printf '%s' "$DISPLAY_LIST"
        exit 0
    fi

    # Bind §: reload list in-place + refresh preview pane (no popup flash).
    # SM_TERM_W passes the popup width to the --render child (which has no tty).
    RELOAD_CMD="SM_TERM_W=$TERM_W $HOME/.tmux/scripts/session-manager-v2.sh --render $VIEW"

    SELECTED=$(echo "$DISPLAY_LIST" | fzf \
        --ansi \
        --sync \
        --no-multi \
        --reverse \
        --no-info \
        --no-separator \
        --header-first \
        --header="$HEADER" \
        --expect="x,.,?,shift-tab,<,>,left,right" \
        --pointer=" " \
        --prompt="  search > " \
        --border=none \
        --delimiter=$'\t' \
        --with-nth=1 \
        --bind "start:pos($CURRENT_LINE)" \
        --bind "§:refresh-preview+reload($RELOAD_CMD)" \
        --bind "tab:transform($HOME/.tmux/scripts/sm-tab-next.sh)" \
        --bind "down:transform($HOME/.tmux/scripts/sm-skip-nav.sh +1)" \
        --bind "up:transform($HOME/.tmux/scripts/sm-skip-nav.sh -1)" \
        --bind "ctrl-n:transform($HOME/.tmux/scripts/sm-skip-nav.sh +1)" \
        --bind "ctrl-p:transform($HOME/.tmux/scripts/sm-skip-nav.sh -1)" \
        --preview="$PREVIEW_CMD" \
        --preview-window=down,40%,~2,follow \
        --color="fg:-1,bg:-1,hl:-1:underline,fg+:0:bold,bg+:7,hl+:1:bold:underline,info:-1,prompt:-1,pointer:-1,marker:-1,spinner:-1,header:-1:dim,border:-1,preview-fg:-1,preview-bg:-1,gutter:-1")

    KEY=$(echo "$SELECTED" | head -1)
    CHOICE=$(echo "$SELECTED" | tail -1)

    # Tab cycling: ← / < = previous, → / > = next
    case "$KEY" in
        "<"|"left")
            case "$VIEW" in
                sessions)   VIEW=help ;;
                menu)       VIEW=sessions ;;
                help)       VIEW=menu ;;
            esac
            continue ;;
        ">"|"right")
            case "$VIEW" in
                sessions)   VIEW=menu ;;
                menu)       VIEW=help ;;
                help)       VIEW=sessions ;;
            esac
            continue ;;
    esac

    [ -z "$CHOICE" ] && exit 0
    # Real session/historique lines carry a trailing TAB + full name. Anything
    # without a TAB is a header / blank / separator → skip. Menu actions also
    # have no tab but are detected by their literal text below.
    case "$CHOICE" in
        *$'\t'*) ;;  # session or historique entry — proceed
        *'open project'*|*'clean cache'*|*'deep clean'*|*'clean history'*|*'kill all'*|*'new hermes'*|*'new claude'*|*'new codex'*|*'aisb terminal'*) ;;  # menu action
        *) continue ;;  # header / blank / decorative
    esac

    # "?" key = jump to help tab
    if [ "$KEY" = "?" ]; then
        VIEW="help"
        continue
    fi

    # Shift+Tab = spawn fresh Claude Code session at $HOME (n1 in c-menu).
    # (fzf does not support alt-tab; shift-tab is the closest Tab variant available.)
    if [ "$KEY" = "shift-tab" ]; then
        new_name="ClaudeRoot"
        _i=2
        while tmux has-session -t "$new_name" 2>/dev/null; do
            new_name="ClaudeRoot-$_i"; ((_i++))
        done
        tmux new-session -d -s "$new_name" -c "$HOME"
        tmux set-environment -t "$new_name" -u ANTHROPIC_API_KEY
        tmux set-option -t "$new_name" remain-on-exit on
        tmux send-keys -t "$new_name" "claude --dangerously-skip-permissions" Enter
        tmux switch-client -t "$new_name"
        exit 0
    fi

    # Action: new hermes (Nous Research Hermes Agent)
    if echo "$CHOICE" | grep -q 'new hermes'; then
        _name="Hermes"; _i=2
        while tmux has-session -t "$_name" 2>/dev/null; do
            _name="Hermes-$_i"; ((_i++))
        done
        tmux new-session -d -s "$_name" -c "$HOME"
        tmux send-keys -t "$_name" 'hermes' Enter
        tmux switch-client -t "$_name"
        exit 0
    fi

    # Action: new gemini (Google Gemini CLI)
    if echo "$CHOICE" | grep -q 'new gemini'; then
        _name="Gemini"; _i=2
        while tmux has-session -t "$_name" 2>/dev/null; do
            _name="Gemini-$_i"; ((_i++))
        done
        tmux new-session -d -s "$_name" -c "$HOME"
        tmux send-keys -t "$_name" '$HOME/.npm-global/bin/gemini' Enter
        tmux switch-client -t "$_name"
        exit 0
    fi

    # Action: new claude (Claude Code)
    if echo "$CHOICE" | grep -q 'new claude'; then
        _name="Claude"; _i=2
        while tmux has-session -t "$_name" 2>/dev/null; do
            _name="Claude-$_i"; ((_i++))
        done
        tmux new-session -d -s "$_name" -c "$HOME"
        tmux send-keys -t "$_name" 'claude' Enter
        tmux switch-client -t "$_name"
        exit 0
    fi

    # Action: new codex (OpenAI Codex)
    if echo "$CHOICE" | grep -q 'new codex'; then
        _name="Codex"; _i=2
        while tmux has-session -t "$_name" 2>/dev/null; do
            _name="Codex-$_i"; ((_i++))
        done
        tmux new-session -d -s "$_name" -c "$HOME"
        tmux set-environment -t "$_name" -u OPENAI_API_KEY
        tmux send-keys -t "$_name" 'unset OPENAI_API_KEY && codex' Enter
        tmux switch-client -t "$_name"
        exit 0
    fi

    # Action: new pi (Pi Agent)
    if echo "$CHOICE" | grep -q 'new pi'; then
        _name="Pi"; _i=2
        while tmux has-session -t "$_name" 2>/dev/null; do
            _name="Pi-$_i"; ((_i++))
        done
        tmux new-session -d -s "$_name" -c "$HOME"
        sleep 0.5
        tmux send-keys -t "$_name" 'pi' Enter
        sleep 0.5
        tmux switch-client -t "$_name" 2>/tmp/pi-switch-debug.log
        exit 0
    fi

    # Action: aisb terminal (attach to bot logs)
    if echo "$CHOICE" | grep -q 'aisb terminal'; then
        if tmux has-session -t AISB-ORACLE 2>/dev/null; then
            tmux switch-client -t AISB-ORACLE
        else
            tmux new-window -n 'aisb-logs' 'journalctl --user -u aisb-bot -f'
        fi
        exit 0
    fi

    # Action: open project — reads from ~/.config/tmux-claude/projects.conf
    # (generated by project-analyzer.sh) with optional fallback to legacy
    # AISB projects.json. Falls back to scanning a few common dirs as a
    # last resort if neither config exists.
    if echo "$CHOICE" | grep -q 'open project'; then
        PROJECTS_CONF="$HOME/.config/tmux-claude/projects.conf"
        PROJECTS_JSON="$HOME/VibeCoding/agentic/agentik-monitor/bot/projects.json"
        # Home always first (shell-only, no Claude auto-launch)
        PROJECT_LINES=$(printf '  %-25s  %s' "Home" "~")
        unset PROJ_PATH_MAP 2>/dev/null
        declare -A PROJ_PATH_MAP

        if [ -f "$PROJECTS_CONF" ]; then
            while IFS='|' read -r pname ppath pcat _rest; do
                [[ "$pname" == \#* || -z "$pname" ]] && continue
                ppath="${ppath%%#*}"; ppath="${ppath%%[[:space:]]}"
                [ -d "$ppath" ] || continue
                PROJ_PATH_MAP[$pname]="$ppath"
            done < "$PROJECTS_CONF"
        fi
        if [ -f "$PROJECTS_JSON" ] && command -v jq >/dev/null 2>&1; then
            while IFS='|' read -r pname ppath; do
                [ -n "${PROJ_PATH_MAP[$pname]:-}" ] && continue
                [ -d "$ppath" ] && PROJ_PATH_MAP[$pname]="$ppath"
            done < <(jq -r '.projects | to_entries[] | "\(.key)|\(.value.path)"' "$PROJECTS_JSON" 2>/dev/null)
        fi

        # Render project list — sorted, paths shortened relative to $HOME
        if [ ${#PROJ_PATH_MAP[@]} -gt 0 ]; then
            db_lines=$(for k in "${!PROJ_PATH_MAP[@]}"; do echo "$k|${PROJ_PATH_MAP[$k]}"; done | sort -f \
                | while IFS='|' read -r pname ppath; do
                    short="${ppath#$HOME/}"
                    [ "$short" = "$ppath" ] || short="~/$short"
                    printf '  %-25s  %s\n' "$pname" "$short"
                done)
            [ -n "$db_lines" ] && PROJECT_LINES="${PROJECT_LINES}"$'\n'"${db_lines}"
        fi

        PROJ_SELECTED=$(echo "$PROJECT_LINES" | fzf \
            --no-multi --reverse --no-info \
            --header="Select project  Enter=open  Esc=back" \
            --prompt="" --pointer=" " --border=none \
            --color="fg:-1,bg:-1,hl:-1:underline,fg+:0:bold,bg+:7,hl+:1:bold:underline,info:-1,prompt:-1,pointer:-1,marker:-1,spinner:-1,header:-1:dim,border:-1,preview-fg:-1,preview-bg:-1,gutter:-1")

        [ -z "$PROJ_SELECTED" ] && continue

        PROJ_NAME=$(echo "$PROJ_SELECTED" | awk '{print $1}')
        if [ "$PROJ_NAME" = "Home" ]; then
            PROJ_PATH="$HOME"
            HOME_MODE=1
        else
            PROJ_PATH="${PROJ_PATH_MAP[$PROJ_NAME]:-}"
            HOME_MODE=0
        fi
        { [ -z "$PROJ_PATH" ] || [ ! -d "$PROJ_PATH" ]; } && continue

        if ! tmux has-session -t "$PROJ_NAME" 2>/dev/null; then
            NEW_SESS="$PROJ_NAME"
        else
            _i=2
            while tmux has-session -t "${PROJ_NAME}-${_i}" 2>/dev/null; do ((_i++)); done
            NEW_SESS="${PROJ_NAME}-${_i}"
        fi
        tmux new-session -d -s "$NEW_SESS" -c "$PROJ_PATH"
        # Home = shell only (no Claude). Projects = auto-launch Claude.
        if [ "$HOME_MODE" != "1" ]; then
            tmux send-keys -t "$NEW_SESS" "claude --dangerously-skip-permissions" Enter
        fi
        tmux switch-client -t "$NEW_SESS"
        exit 0
    fi

    # Action: clean cache (fast — kernel page cache + /tmp junk)
    if echo "$CHOICE" | grep -q 'clean cache'; then
        sync
        echo 3 | sudo tee /proc/sys/vm/drop_caches > /dev/null 2>&1
        rm -rf /tmp/.maniac-* /tmp/browser-screenshots/* /tmp/sm-test* 2>/dev/null
        continue
    fi

    # Action: deep clean (heavy disk reclaim — runs script with progress + pause)
    if echo "$CHOICE" | grep -q 'deep clean'; then
        clear
        bash "$HOME/.tmux/scripts/sm-deep-clean.sh"
        continue
    fi

    # Action: clean history (wipe kill log + protection state)
    if echo "$CHOICE" | grep -q 'clean history'; then
        clear
        bash "$HOME/.tmux/scripts/sm-clean-history.sh"
        continue
    fi

    # Action: kill all (except current)
    if echo "$CHOICE" | grep -q 'kill all'; then
        for s in $(tmux list-sessions -F '#{session_name}' 2>/dev/null | grep -v "^${CURRENT_SESSION}$"); do
            kill_with_history "$s" "kill-all"
        done
        continue
    fi

    # ── Session actions ──
    TARGET=$(extract_name "$CHOICE")

    # "." key = toggle protection
    if [ "$KEY" = "." ]; then
        if [ -n "$TARGET" ]; then
            toggle_protection "$TARGET"
            # If manually unprotecting, mark it so auto-protect doesn't re-protect
            if ! is_protected "$TARGET"; then
                touch "$PROTECT_DIR/${TARGET}.manual-unprotect"
            else
                rm -f "$PROTECT_DIR/${TARGET}.manual-unprotect"
            fi
        fi
        continue
    fi

    # "x" key = kill session
    if [ "$KEY" = "x" ]; then
        is_protected "$TARGET" && continue
        if [ "$TARGET" = "$CURRENT_SESSION" ]; then
            OTHER=$(tmux list-sessions -F '#{session_name}' | grep -v "^${TARGET}$" | head -1)
            if [ -n "$OTHER" ]; then
                tmux switch-client -t "$OTHER"
                CURRENT_SESSION="$OTHER"
                kill_with_history "$TARGET" "manual"
            fi
        else
            kill_with_history "$TARGET" "manual"
        fi
        continue
    fi

    # ── Historique view: Enter recreates the killed session at its project path ──
    if [ "$VIEW" = "historique" ] && [ -n "$TARGET" ]; then
        # If somehow it's already alive, just switch
        if tmux has-session -t "$TARGET" 2>/dev/null; then
            tmux switch-client -t "$TARGET"
            exit 0
        fi
        project_key "$TARGET"; rpkey="$REPLY"
        rpath=""
        case "$rpkey" in
            Home)    rpath="$HOME" ;;
            _system) clear; echo "  System sessions can't be reopened from history."; sleep 2; continue ;;
            *)
                # Look up project path: projects.conf first, then legacy projects.json
                PROJECTS_CONF="$HOME/.config/tmux-claude/projects.conf"
                if [ -f "$PROJECTS_CONF" ]; then
                    while IFS='|' read -r pname ppath _rest; do
                        [[ "$pname" == \#* || -z "$pname" ]] && continue
                        if [ "$pname" = "$rpkey" ]; then
                            ppath="${ppath%%#*}"; ppath="${ppath%%[[:space:]]}"
                            rpath="$ppath"
                            break
                        fi
                    done < "$PROJECTS_CONF"
                fi
                if [ -z "$rpath" ]; then
                    PROJECTS_JSON="$HOME/VibeCoding/agentic/agentik-monitor/bot/projects.json"
                    if [ -f "$PROJECTS_JSON" ] && command -v jq >/dev/null 2>&1; then
                        rpath=$(jq -r --arg n "$rpkey" '.projects[$n].path // empty' "$PROJECTS_JSON" 2>/dev/null)
                    fi
                fi
                [ -z "$rpath" ] && rpath="$HOME"
                ;;
        esac
        if [ ! -d "$rpath" ]; then
            clear; echo "  Project path missing: $rpath"; sleep 2; continue
        fi
        tmux new-session -d -s "$TARGET" -c "$rpath"
        tmux set-environment -t "$TARGET" -u ANTHROPIC_API_KEY
        tmux set-option -t "$TARGET" remain-on-exit on
        tmux switch-client -t "$TARGET"
        exit 0
    fi

    # Enter = switch to session
    [ -n "$TARGET" ] && [ "$TARGET" != "$CURRENT_SESSION" ] && tmux switch-client -t "$TARGET"
    exit 0
done
