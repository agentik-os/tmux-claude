CURRENT_SESSION=$(tmux display-message -p '#S')
NOW=$(date +%s)
TMPDIR_SM="/tmp/.sm-$$"
PROTECT_DIR="/tmp/.tmux-protected"
HISTORY_FILE="/tmp/.tmux-kill-history"
AUTOPROTECT_DIR="/tmp/.tmux-autoprotect"
mkdir -p "$TMPDIR_SM" "$PROTECT_DIR" "$AUTOPROTECT_DIR"
trap "rm -rf '$TMPDIR_SM'" EXIT
touch "$HISTORY_FILE"

# ── Project → category map from projects.json ──
# Used to bucket sessions into work / clients / life / aisb.
# Sessions whose project_key isn't in projects.json fall back to "aisb"
# (i.e. "stuff outside current context").
declare -A PROJECT_CAT
# Project registry — primary source: ~/.config/tmux-claude/projects.conf
# (generated by project-analyzer.sh on install). Optional fallback: AISB
# projects.json if present (legacy / local override).
PROJECTS_CONF="$HOME/.config/tmux-claude/projects.conf"
PROJECTS_JSON="$HOME/VibeCoding/agentic/agentik-monitor/bot/projects.json"
if [ -f "$PROJECTS_CONF" ]; then
    while IFS='|' read -r pname ppath pcat _rest; do
        [[ "$pname" == \#* || -z "$pname" ]] && continue
        ppath="${ppath%%#*}"; ppath="${ppath%%[[:space:]]}"
        pcat="${pcat%%[[:space:]]*}"
        [ -n "$pcat" ] && PROJECT_CAT[$pname]="$pcat"
    done < "$PROJECTS_CONF"
fi
if [ -f "$PROJECTS_JSON" ] && command -v jq >/dev/null 2>&1; then
    while IFS='|' read -r pname ppath; do
        [ -n "${PROJECT_CAT[$pname]:-}" ] && continue   # don't override conf
        case "$ppath" in
            */work/*)     PROJECT_CAT[$pname]="work" ;;
            */clients/*)  PROJECT_CAT[$pname]="clients" ;;
            */1-life*)    PROJECT_CAT[$pname]="life" ;;
        esac
    done < <(jq -r '.projects | to_entries[] | "\(.key)|\(.value.path)"' "$PROJECTS_JSON" 2>/dev/null)
fi

# Known multi-segment project keys (longest first) so `project_key` doesn't
# truncate names like `Agentik-Academy-worker-…` to `Agentik`. Without this,
# any project whose name contains a hyphen (Agentik-Academy, CAIO-Academy, …)
# would have its workers grouped under the wrong bucket in the session menu.
KNOWN_PROJECTS=()
if [ -f "$PROJECTS_JSON" ] && command -v jq >/dev/null 2>&1; then
    while IFS= read -r _pkey; do
        [ -n "$_pkey" ] && KNOWN_PROJECTS+=("$_pkey")
    done < <(jq -r '.projects | keys[]' "$PROJECTS_JSON" 2>/dev/null \
             | awk '{ print length, $0 }' | sort -rn | cut -d' ' -f2-)
fi

project_category() {
    local pkey="$1"
    case "$pkey" in
        Home)    echo "home";    return ;;
        _system) echo "aisb";    return ;;
    esac
    local cat="${PROJECT_CAT[$pkey]}"
    if [ -n "$cat" ]; then echo "$cat"; else echo "aisb"; fi
}

# Terminal width for adaptive columns
# In --render mode (fzf reload child) tput has no tty → use the parent's TERM_W
# passed via env var. Otherwise probe the actual terminal/popup width.
TERM_W=${SM_TERM_W:-$(tput cols 2>/dev/null || echo 80)}

# Dynamic NAME_MAX: use all available terminal width.
# Right-side fixed cost: ram(5) + age(6) + branch(10) + 3 inter-col spaces = 24
# Left prefix cost: 2-space indent + marker(1) + space + icon(1) + space + protect(1) + space = 8
# Double-space after name = 2
# Total fixed = 34 → NAME_MAX = TERM_W - 34
NAME_MAX=$((TERM_W - 65))    # default: name area + age bar + progress + ram + age + branch + gutters
[ "$NAME_MAX" -lt 18 ] && NAME_MAX=18
[ "$NAME_MAX" -gt 50 ] && NAME_MAX=50    # generous cap — fits ~99% of session names without truncation
                                          # while keeping the whole row packed (no big gaps anywhere)
PATH_MAX=$((TERM_W - 60))
[ "$PATH_MAX" -lt 8 ] && PATH_MAX=8

# short_name: when a session is rendered inside a tree (its project parent is
# already visible above), strip the redundant project prefix from the display.
# The full session name is still preserved in the hidden TAB field for
# tmux switch-client and for search.
short_name() {
    local name="$1" pkey="$2"
    [ -z "$pkey" ] && { REPLY="$name"; return; }
    case "$name" in
        oracle-"${pkey}")          REPLY="oracle"; return ;;
        oracle-"${pkey}"-*)        REPLY="oracle-${name#oracle-${pkey}-}"; return ;;
        "${pkey}"-oracle)          REPLY="oracle"; return ;;
        "${pkey}"-oracle-*)        REPLY="oracle-${name#${pkey}-oracle-}"; return ;;
        "${pkey}"-worker-*)        REPLY="${name#${pkey}-}"; return ;;
    esac
    REPLY="$name"
}

# All helper functions write to $REPLY (bash convention) — eliminates the
# subshell fork from $(func "$arg") in hot loops. ~10× speed-up at scale.
truncate_str() {
    local str="$1" max="$2"
    if [ "${#str}" -gt "$max" ]; then
        REPLY="${str:0:$((max-1))}…"
    else
        REPLY="$str"
    fi
}

# truncate_smart: keep right side if mode=start (preserves ticket IDs like CAU-95).
truncate_smart() {
    local str="$1" max="$2" mode="${3:-end}"
    if [ "${#str}" -le "$max" ]; then
        REPLY="$str"
        return
    fi
    if [ "$mode" = "start" ]; then
        REPLY="…${str: -$((max-1))}"
    else
        REPLY="${str:0:$((max-1))}…"
    fi
}

# ANSI helpers for warnings (only place color is permitted by user policy).
RED=$'\033[31m'
YEL=$'\033[33m'
RST=$'\033[0m'

human_time() {
    local secs=$1
    if   [ "$secs" -lt 60 ];    then REPLY="${secs}s"
    elif [ "$secs" -lt 3600 ];  then REPLY="$((secs/60))m"
    elif [ "$secs" -lt 86400 ]; then REPLY="$((secs/3600))h$((secs%3600/60))m"
    else                              REPLY="$((secs/86400))d$((secs%86400/3600))h"
    fi
}

# Bulk-load AISB progress state for ALL sessions in ONE awk pass over every
# progress.json file. ~110 files processed in one fork instead of bash reading
# each file line-by-line (was the dominant render cost on hosts with many
# orchestration files). Populates global PROGRESS_STATE keyed by session name.
load_all_progress() {
    unset PROGRESS_STATE 2>/dev/null
    declare -gA PROGRESS_STATE
    shopt -s nullglob
    local files=( "$HOME/.aisb/state/oracle-"*.progress.json "$HOME/.aisb/state/worker-"*.progress.json )
    shopt -u nullglob
    [ ${#files[@]} -eq 0 ] && return
    while IFS='|' read -r sname pstr; do
        [ -n "$sname" ] && PROGRESS_STATE[$sname]="$pstr"
    done < <(awk '
        FNR == 1 {
            # Extract session name from filename
            base = FILENAME
            sub(/.*\//, "", base)
            sub(/\.progress\.json$/, "", base)
            sub(/^oracle-/, "", base)
            sub(/^worker-/, "", base)
            sname = base
            sessions[sname] = 1
            total[sname] = ""
            done_n[sname] = ""
            blocked[sname] = 0
        }
        /"todos_total"/ {
            n = match($0, /[0-9]+/)
            if (n) total[sname] = substr($0, RSTART, RLENGTH)
        }
        /"todos_completed"/ {
            n = match($0, /[0-9]+/)
            if (n) done_n[sname] = substr($0, RSTART, RLENGTH)
        }
        /"status"[[:space:]]*:[[:space:]]*"blocked"/ { blocked[sname] = 1 }
        END {
            for (s in sessions) {
                if (total[s] != "" && total[s] != "0") {
                    suffix = blocked[s] ? "⚠" : ""
                    printf "%s|%s/%s%s\n", s, done_n[s], total[s], suffix
                }
            }
        }
    ' "${files[@]}" 2>/dev/null)
}

# 8-char age bar — log-ish scale on 0..24h.
#   <5min=1 ▰ | <15min=2 | <1h=3 | <3h=4 | <8h=5 | <12h=6 | <24h=7 | >=24h=8
age_bar() {
    local secs="${1:-0}" n=0
    if   [ "$secs" -lt 300 ];   then n=1
    elif [ "$secs" -lt 900 ];   then n=2
    elif [ "$secs" -lt 3600 ];  then n=3
    elif [ "$secs" -lt 10800 ]; then n=4
    elif [ "$secs" -lt 28800 ]; then n=5
    elif [ "$secs" -lt 43200 ]; then n=6
    elif [ "$secs" -lt 86400 ]; then n=7
    else                              n=8
    fi
    local out="" i=0
    while [ "$i" -lt 8 ]; do
        if [ "$i" -lt "$n" ]; then out+="▰"; else out+="▱"; fi
        i=$((i+1))
    done
    REPLY="$out"
}

human_mb() {
    local kb=$1
    if   [ "$kb" -lt 1024 ];    then REPLY="${kb}K"
    elif [ "$kb" -lt 1048576 ]; then REPLY="$((kb/1024))M"
    else
        local g=$((kb / 1048576))
        local d=$(( (kb % 1048576) * 10 / 1048576 ))
        REPLY="${g}.${d}G"
    fi
}

is_protected() {
    [ -f "$PROTECT_DIR/$1" ]
}

toggle_protection() {
    local sess="$1"
    if is_protected "$sess"; then
        rm -f "$PROTECT_DIR/$sess"
    else
        touch "$PROTECT_DIR/$sess"
    fi
}

# ── Auto-protect: protect working sessions, unprotect idle >10min ──
auto_protect_check() {
    local sess="$1" status="$2"
    local ap_file="$AUTOPROTECT_DIR/$sess"
    if [ "$status" = "work" ]; then
        # Auto-protect if working and not manually unprotected
        if [ ! -f "$PROTECT_DIR/${sess}.manual-unprotect" ]; then
            touch "$PROTECT_DIR/$sess"
            touch "$ap_file"  # mark as auto-protected
        fi
    elif [ "$status" = "idle" ] && [ -f "$ap_file" ]; then
        # Was auto-protected, now idle — check if idle >10min
        local ap_age=$(( NOW - $(stat -c %Y "$ap_file" 2>/dev/null || echo "$NOW") ))
        if [ "$ap_age" -gt 600 ]; then
            rm -f "$PROTECT_DIR/$sess" "$ap_file"
        fi
    fi
}

# ── Kill with history logging ──
kill_with_history() {
    local sess="$1"
    local reason="${2:-manual}"
    # Log to history (keep last 20)
    echo "$(date '+%H:%M:%S') | $sess | $reason" >> "$HISTORY_FILE"
    tail -20 "$HISTORY_FILE" > "$HISTORY_FILE.tmp" && mv "$HISTORY_FILE.tmp" "$HISTORY_FILE"
    tmux kill-session -t "$sess" 2>/dev/null
}

# ── RAM usage for a session (awk tree walk over shared PS_SNAP, zero forks) ──
get_session_ram() {
    local sess="$1" outfile="$2"
    local pane_pids
    # Read pane_pids from batched PANES_SNAP instead of forking tmux per session
    pane_pids=$(awk -F'\t' -v s="$sess" '$1==s{print $2}' "$PANES_SNAP" 2>/dev/null | tr '\n' ' ')
    if [ -z "$pane_pids" ] || [ ! -f "$PS_SNAP" ]; then
        echo 0 > "$outfile"
        return
    fi
    # Full tree walk via awk: sum RSS of all descendants of pane_pids
    awk -v roots="$pane_pids" '
        { ppid=$2; pid=$1; rss[pid]=$3; child[ppid]=child[ppid]" "pid }
        END {
            n=split(roots, r, " ")
            total=0
            for (i=1; i<=n; i++) if (r[i]!="") { q[++qn]=r[i] }
            while (qn>0) {
                cur=q[qn]; qn--
                m=split(child[cur], kids, " ")
                for (j=1; j<=m; j++) {
                    k=kids[j]
                    if (k!="") { total += rss[k]; q[++qn]=k }
                }
            }
            print total
        }' "$PS_SNAP" > "$outfile"
}

# ── Deep Claude status detection (uses PS_SNAP + PANES_SNAP, zero ps/pgrep/tmux forks) ──
detect_claude_status() {
    local session="$1" outfile="$2"
    local result="" detail=""

    # Read panes for this session from batched snapshot
    local pane_claude_parents=""
    pane_claude_parents=$(awk -F'\t' -v s="$session" '$1==s && $3=="claude"{print $2}' "$PANES_SNAP" 2>/dev/null | tr '\n' ' ')

    if [ -z "$pane_claude_parents" ] || [ ! -f "$PS_SNAP" ]; then
        echo "shell|0|0|" > "$outfile"
        return
    fi

    # One awk call computes: claude_count, total_cpu, subagent_count, real_work tool
    local stats
    stats=$(awk -v roots="$pane_claude_parents" '
        BEGIN {
            n=split(roots, r, " ")
            for (i=1; i<=n; i++) if (r[i]!="") rootset[r[i]]=1
            # ignored commands when checking real_work
            ignore="ps sleep cat grep tail head wc sed awk echo test zsh bash sh tee tr sort xargs date timeout node claude npm npx tsx"
            ni=split(ignore, ig, " "); for (i=1; i<=ni; i++) ignored[ig[i]]=1
        }
        {
            pid=$1; ppid=$2; cpu=$4; comm=$5
            rss_idx=3 # unused here
            child[ppid]=child[ppid]" "pid
            pcomm[pid]=comm
            pcpu[pid]=cpu
        }
        END {
            claude_count=0; subagent_count=0; total_cpu=0; real_work=0; work_tool=""
            # top-level claude PIDs = direct children of pane pids whose comm is "claude"
            delete claude_pids
            for (pp in rootset) {
                m=split(child[pp], kids, " ")
                for (j=1; j<=m; j++) {
                    k=kids[j]
                    if (k!="" && pcomm[k]=="claude") {
                        claude_pids[k]=1
                        claude_count++
                    }
                }
            }
            if (claude_count==0) { print "shell|0|0|"; exit }

            # Walk full descendant tree of all claude_pids
            for (cp in claude_pids) {
                total_cpu += int(pcpu[cp])
                # BFS
                qn=0; q[++qn]=cp
                while (qn>0) {
                    cur=q[qn]; qn--
                    m=split(child[cur], kids, " ")
                    for (j=1; j<=m; j++) {
                        k=kids[j]
                        if (k=="") continue
                        q[++qn]=k
                        kc=pcomm[k]
                        if (kc=="claude") subagent_count++
                        if (!real_work && !(kc in ignored)) {
                            # skip mcp-*, firecrawl*, chrome-*, playwright* prefixes
                            if (kc !~ /^(mcp-|firecrawl|chrome-|playwright)/) {
                                real_work=1
                                work_tool=kc
                            }
                        }
                    }
                }
            }
            printf "OK|%d|%d|%d|%d|%s\n", claude_count, total_cpu, subagent_count, real_work, work_tool
        }' "$PS_SNAP")

    # Shell-only early exit path
    if [ "${stats%%|*}" = "shell" ]; then
        echo "shell|0|0|" > "$outfile"
        return
    fi

    local claude_count total_cpu subagent_count real_work work_tools
    IFS='|' read -r _ claude_count total_cpu subagent_count real_work work_tools <<< "$stats"

    # Fast path: decide without capture-pane if ps data is conclusive
    if [ "$subagent_count" -gt 0 ]; then
        result="work"; detail="${subagent_count}agents"
    elif [ "$real_work" -eq 1 ]; then
        result="work"; detail="${work_tools%% *}"
    elif [ "$total_cpu" -gt 15 ]; then
        result="work"; detail="cpu${total_cpu}%"
    else
        # Ambiguous: need a capture-pane to tell idle-at-prompt vs streaming
        last_lines=$(tmux capture-pane -t "$session" -p -S -6 2>/dev/null)
        has_prompt=0; is_streaming=0
        case "$last_lines" in *❯*) has_prompt=1 ;; esac
        case "$last_lines" in
            *"esc to interrupt"*|*"⏳"*) is_streaming=1 ;;
            *Thinking*|*Planning*)       is_streaming=1 ;;
        esac
        if [ "$is_streaming" -eq 1 ]; then
            result="work"; detail="stream"
        elif [ "$has_prompt" -eq 1 ]; then
            result="idle"; detail=""
        else
            result="work"; detail="active"
        fi
    fi

    echo "${result}|${subagent_count}|${claude_count}|${detail}" > "$outfile"
}

# ── Classify session into group ──
classify_session() {
    local name="$1"
    [[ "$name" == earthbit* ]] && { echo "system"; return; }
    [[ "$name" == AISB-* ]] && { echo "system"; return; }
    [[ "$name" == oracle-* ]] && { echo "oracle"; return; }
    [[ "$name" == Home* ]] && { echo "home"; return; }
    [[ "$name" == c-* ]] && { echo "home"; return; }
    echo "worker"
}

# ── Extract project key from session name (for grouping oracle+workers together) ──
# oracle-Causio         → Causio
# oracle-Causio-2       → Causio
# Causio-linear-CAU-42  → Causio
# Causio-fix-auth       → Causio
# DentistryGPT-verify   → DentistryGPT
# Home                  → Home
# Home-4                → Home
# earthbit-daemon       → _system
# AISB-bot              → _system
project_key() {
    local name="$1"
    case "$name" in
        earthbit*) REPLY="_system"; return ;;
        AISB-*)    REPLY="_system"; return ;;
        Home*)     REPLY="Home"; return ;;
        c-*)       REPLY="Home"; return ;;
    esac
    if [[ "$name" == oracle-* ]]; then
        local stripped="${name#oracle-}"
        stripped="${stripped%-[0-9]}"
        stripped="${stripped%-[0-9][0-9]}"
        REPLY="$stripped"
        return
    fi
    # Longest-prefix match against known multi-segment project keys so that
    # `Agentik-Academy-worker-B-…` groups under `Agentik-Academy`, not `Agentik`.
    local _proj
    for _proj in "${KNOWN_PROJECTS[@]}"; do
        case "$name" in
            "$_proj"|"$_proj"-*) REPLY="$_proj"; return ;;
        esac
    done
    REPLY="${name%%-*}"
}

project_role() {
    case "$1" in
        oracle-*)   REPLY=0 ;;
        *-oracle)   REPLY=0 ;;
        *-oracle-*) REPLY=0 ;;
        Home*)      REPLY=2 ;;
        c-*)        REPLY=2 ;;
        earthbit*)  REPLY=3 ;;
        AISB-*)     REPLY=3 ;;
        *)          REPLY=1 ;;
    esac
}

oracle_idx() {
    case "$1" in
        oracle-*-[0-9]|oracle-*-[0-9][0-9])  REPLY="${1##*-}"; return ;;
        oracle-*)                             REPLY="1"; return ;;
        *-oracle-[0-9]|*-oracle-[0-9][0-9])  REPLY="${1##*-}"; return ;;
        *-oracle)                             REPLY="1"; return ;;
    esac
    if [[ "$1" == *-worker-* ]]; then
        local rest="${1#*-worker-}"
        local idx="${rest%%-*}"
        if [[ "$idx" =~ ^[0-9]+$ ]]; then REPLY="$idx"; return; fi
    fi
    REPLY="1"
}

